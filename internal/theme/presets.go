var presets = []Theme{presetDark, presetLight, presetContrast}

var presetIndex = func() map[string]Theme {
	m := make(map[string]Theme, len(presets))
	for _, t := range presets {
		m[t.ID] = t
	}
	return m
}()

func presetByID(id string) (Theme, bool) {
	t, ok := presetIndex[id]
	return t, ok
}

func defaultTheme() Theme {
	return presetDark
}
